export const menuStrings = (locale: TypedLocale): MenuStrings => STRINGS[locale] ?? STRINGS.en

/** a refused guest action (`GuestError`, rem0018 phase 3) in the guest's words */
export const guestErrorText = (error: GuestError, t: MenuStrings): string => {
  if (error === 'closed') return t.ordersWhenOpen
  if (error === 'failed') return t.failed
  return t[error]
}
